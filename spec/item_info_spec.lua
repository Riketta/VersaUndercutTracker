require("VersaUndercutTracker.domain.types")
local ItemInfo = require("VersaUndercutTracker.adapters.outbound.item_info")

describe("item_info adapter (pure parts)", function()
    it("seeds exact names from own-lot item links", function()
        local info = ItemInfo.new()
        info:learnFromLink(10123, "|Hitem:10123::::::::60:1486::1:1:12747::::::|h[Ornate Circlet of the Channeler]|h")
        assert.equals("Ornate Circlet of the Channeler", info:name(10123))
    end)

    it("never overwrites a learned name with a later link", function()
        local info = ItemInfo.new()
        info:learnFromLink(10123, "|Hitem:10123::::|h[First Name]|h")
        info:learnFromLink(10123, "|Hitem:10123::::|h[Second Name]|h")
        assert.equals("First Name", info:name(10123))
    end)

    it("ignores missing or bracket-less links without caching junk", function()
        local info = ItemInfo.new()
        info:learnFromLink(1, nil)
        info:learnFromLink(2, "")
        info:learnFromLink(3, "no brackets here")
        assert.is_nil(info.nameCache[1])
        assert.is_nil(info.nameCache[2])
        assert.is_nil(info.nameCache[3])
    end)
end)
